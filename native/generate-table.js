'use strict'

// Public Ed25519 fixed-base table, generated at build time with exact integers.
// The shader uses affine cached points (y-x, y+x, 2*d*x*y) for mixed additions.
const fs = require('bare-fs')

const prime = (1n << 255n) - 19n
const mod = (x) => ((x % prime) + prime) % prime
function power(x, n) {
  let out = 1n

  for (; n; n >>= 1n, x = mod(x * x)) if (n & 1n) out = mod(out * x)

  return out
}

const inverse = (x) => power(x, prime - 2n)
const d2 = mod(-243330n * inverse(121666n))
const identity = [0n, 1n, 1n, 0n]
function add([x, y, z, t], [qx, qy, qz, qt]) {
  const a = mod((y - x) * (qy - qx))
  const b = mod((y + x) * (qy + qx))
  const c = mod(t * qt * d2)
  const dd = mod(2n * z * qz)
  const e = mod(b - a),
    f = mod(dd - c),
    g = mod(dd + c),
    h = mod(b + a)

  return [mod(e * f), mod(h * g), mod(g * f), mod(e * h)]
}
let base = [
  15112221349535400772501151409588531511454012693041857206046113283949847762202n,
  46316835694926478169428394003475163141307993866256225615783033603165251855960n,
  1n,
  0n
]
base[3] = mod(base[0] * base[1])

// Alternating 26/25-bit limbs cover exactly 255 bits (the ref10 radix).
const widths = Array.from({ length: 10 }, (_, i) => (i % 2 === 0 ? 26 : 25))
const shifts = widths.map((_, i) => Math.ceil(i * 25.5))
const table = new Uint32Array(32 * 3 * 10 * 129)

for (let window = 0; window < 32; window++) {
  const points = [],
    products = []
  let point = identity,
    product = 1n

  for (let digit = 0; digit < 129; digit++) {
    points.push(point)
    products.push(product)
    product = mod(product * point[2])
    point = add(point, base)
  }
  // One inversion per window, instead of one per point.
  let reciprocal = inverse(product)

  for (let digit = 128; digit >= 0; digit--) {
    const [x, y, z] = points[digit]
    const iz = mod(reciprocal * products[digit])
    reciprocal = mod(reciprocal * z)

    const ax = mod(x * iz),
      ay = mod(y * iz)

    const coords = [mod(ay - ax), mod(ay + ax), mod(d2 * ax * ay)]

    for (let coord = 0; coord < 3; coord++) {
      for (let limb = 0; limb < 10; limb++) {
        table[((window * 3 + coord) * 10 + limb) * 129 + digit] = Number(
          (coords[coord] >> BigInt(shifts[limb])) & ((1n << BigInt(widths[limb])) - 1n)
        )
      }
    }
  }

  for (let i = 0; i < 8; i++) base = add(base, base)
}

const rows = []

for (let i = 0; i < table.length; i += 8) {
  rows.push(
    '  ' +
      Array.from(
        table.subarray(i, i + 8),
        (n) => '0x' + n.toString(16).padStart(8, '0') + 'u'
      ).join(', ')
  )
}
fs.writeFileSync(
  Bare.argv[2],
  '// Generated by generate-table.js; public data only.\nconst uint32_t basepoint_table[] = {\n' +
    rows.join(',\n') +
    '\n};\n'
)

// Literal indices let shader compilers keep field limbs in registers instead of
// spilling dynamically indexed convolution arrays into per-invocation memory.
const functions = [
  `int64_t product(int a, int b) {
  int high, low;
  imulExtended(a, b, high, low);

  return packInt2x32(ivec2(low, high));
}`
]

const reduce = ['Field reduce(int64_t t[10]) {']

// Two interleaved carry chains center the limbs using the ref10 schedule.
for (const limb of [0, 4, 1, 5, 2, 6, 3, 7, 4, 8, 9, 0]) {
  const bits = widths[limb]
  reduce.push(
    '  {',
    `    int64_t c = (t[${limb}] + (int64_t(1) << ${bits - 1})) >> ${bits};`,
    limb === 9 ? '    t[0] += 19 * c;' : `    t[${limb + 1}] += c;`,
    `    t[${limb}] -= c * (int64_t(1) << ${bits});`,
    '  }'
  )
}

reduce.push('  Field result;')
for (let limb = 0; limb < 10; limb++) reduce.push(`  result.v[${limb}] = int(t[${limb}]);`)
reduce.push('  return result;', '}')
functions.push(reduce.join('\n'))

for (const square of [false, true]) {
  const lines = [
    `Field ${square ? 'square(Field a)' : 'mul(Field a, Field b)'} {`,
    '  int64_t t[10];'
  ]

  for (let limb = 0; limb < 10; limb++) {
    const grouped = new Map()

    for (let i = 0; i < 10; i++) {
      for (let j = square ? i : 0; j < 10; j++) {
        if ((i + j) % 10 !== limb) continue

        const exponent = shifts[i] + shifts[j]
        const scale =
          (square && i !== j ? 2 : 1) *
          (exponent >= 255 ? 19 : 1) *
          2 ** ((exponent % 255) - shifts[limb])
        const term = `product(a.v[${i}], ${square ? 'a' : 'b'}.v[${j}])`
        if (!grouped.has(scale)) grouped.set(scale, [])
        grouped.get(scale).push(term)
      }
    }

    const terms = [...grouped].map(([scale, products]) => {
      const sum = products.join(' + ')
      return scale === 1 ? sum : `${scale} * (${sum})`
    })
    lines.push(`  t[${limb}] = ${terms.join(' + ')};`)
  }

  lines.push('  return reduce(t);', '}')
  functions.push(lines.join('\n'))
}

const pack = ['void pack(Field a, out uint pk[8]) {']

for (let word = 0; word < 8; word++) {
  const terms = []

  for (let limb = 0; limb < 10; limb++) {
    const offset = shifts[limb] - word * 32
    if (offset >= 32 || offset + widths[limb] <= 0) continue

    terms.push(`(uint(a.v[${limb}]) ${offset < 0 ? '>>' : '<<'} ${Math.abs(offset)})`)
  }

  pack.push(`  pk[${word}] = ${terms.join(' | ')};`)
}

pack.push('}')
functions.push(pack.join('\n'))
fs.writeFileSync(
  Bare.argv[3],
  '// Generated exact radix-2^25.5 arithmetic.\n' + functions.join('\n')
)
